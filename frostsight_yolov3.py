"""## ⚡ Cell 8 — Inference Speed Benchmark [NEW-4]

> 100 passes (10 warmup), single image, reports FPS / ms-per-image / peak VRAM.
"""

def benchmark_speed(model_name: str, weights_path: str) -> dict:
    """
    Measure inference latency (ms/img) and throughput (FPS).
    Runs CFG['bench_n_runs'] passes; first 10 are warmup.
    """
    print(f"\n[BENCH] Benchmarking {model_name} …")
    if not os.path.exists(weights_path):
        print(f"[BENCH] Weights not found: {weights_path}")
        return {}
    try:
        import torch
        from ultralytics import YOLO

        model  = YOLO(weights_path)
        device = CFG["device"]
        dummy  = np.random.randint(0, 255,
                    (CFG["img_size"], CFG["img_size"], 3), dtype=np.uint8)
        n_runs = CFG["bench_n_runs"]

        for _ in range(10):                          # warmup
            model.predict(dummy, verbose=False, device=device)

        if torch.cuda.is_available():
            torch.cuda.reset_peak_memory_stats()

        t_start = time.perf_counter()
        for _ in range(n_runs):
            model.predict(dummy, verbose=False, device=device)
        elapsed = time.perf_counter() - t_start

        ms_per_img = (elapsed / n_runs) * 1000
        fps        = n_runs / elapsed
        vram_mb    = (torch.cuda.max_memory_allocated() / 1024 ** 2
                      if torch.cuda.is_available() else float("nan"))

        result = {
            "model": model_name, "ms_per_img": round(ms_per_img, 2),
            "fps": round(fps, 1), "vram_peak_mb": round(vram_mb, 1),
            "n_runs": n_runs,
        }
        print(f"  {model_name}: {ms_per_img:.1f} ms/img | {fps:.1f} FPS | VRAM: {vram_mb:.0f} MB")
        return result
    except Exception as e:
        print(f"[BENCH] Error: {e}")
        return {"model": model_name, "error": str(e)}

print("✓ benchmark_speed() defined")

"""## 🏋️ Cell 9 — Multi-Seed Training Function [R1-A]

> Trains a single model across all seeds. After each seed: validates on test split, collects FCR and per-class metrics.
"""

def train_model(model_name: str, model_weight, data_yaml: str,
                seeds: list, task: str = "segment") -> dict:
    """
    Train a model across multiple seeds.
    Returns aggregated metrics + per-class table + FCR.
    """
    from ultralytics import YOLO

    seed_metrics, seed_fcr, per_class_frames = [], [], []

    print(f"\n{'─'*60}")
    print(f"[TRAIN] {model_name}  |  task={task}  |  seeds={seeds}")
    print(f"{'─'*60}")

    for seed in seeds:
        set_seed(seed)
        run_name = f"{model_name}_seed{seed}"
        save_dir = os.path.join(CFG["output_dir"], run_name)

        model = build_aspp_model() if model_name == "YOLOv11s+ASPP" else YOLO(model_weight)

        t0 = time.time()
        train_results = model.train(
            data=data_yaml, epochs=CFG["epochs"], imgsz=CFG["img_size"],
            batch=CFG["batch"], workers=CFG["workers"], device=CFG["device"],
            seed=seed, project=CFG["output_dir"], name=run_name, exist_ok=True,
            verbose=False,
            degrees=45, flipud=0.5, fliplr=0.5, mosaic=1.0,
            mixup=0.1, hsv_h=0.015, hsv_s=0.7, hsv_v=0.4,
        )
        elapsed = time.time() - t0

        # Use YOLO's actual save directory (avoids _2/_3 suffix issue)
        actual_save_dir = str(train_results.save_dir)
        best_weights = os.path.join(actual_save_dir, "weights", "best.pt")

        # Fallback: glob search if still not found
        if not os.path.exists(best_weights):
            candidates = glob.glob(os.path.join(
                CFG["output_dir"], f"{model_name}_seed{seed}*", "weights", "best.pt"))
            if candidates:
                best_weights = sorted(candidates)[-1]
                print(f"  [INFO] Fallback weights found: {best_weights}")
            else:
                print(f"  [ERROR] best.pt not found for {model_name} seed={seed}")
                continue
        val_model    = YOLO(best_weights)
        val_results  = val_model.val(
            data=data_yaml, split="test",
            imgsz=CFG["img_size"], device=CFG["device"], verbose=False,
        )

        m   = val_results.results_dict
        row = {
            "seed"        : seed,
            "mAP50"       : m.get("metrics/mAP50(B)",    m.get("metrics/mAP50(M)",    0)),
            "mAP50_95"    : m.get("metrics/mAP50-95(B)", m.get("metrics/mAP50-95(M)", 0)),
            "precision"   : m.get("metrics/precision(B)", m.get("metrics/precision(M)", 0)),
            "recall"      : m.get("metrics/recall(B)",   m.get("metrics/recall(M)",   0)),
            "train_hr"    : round(elapsed / 3600, 3),
            "best_weights": best_weights,
        }
        seed_metrics.append(row)

        fcr_info         = compute_fcr(val_results)
        fcr_info["seed"] = seed
        seed_fcr.append(fcr_info)

        pc_df = evaluate_per_class(val_results, model_name, seed)
        per_class_frames.append(pc_df)

        print(f"  seed={seed} | mAP50={row['mAP50']:.4f} | "
              f"mAP50-95={row['mAP50_95']:.4f} | FCR(macro)={fcr_info['macro_FCR']}")

    df  = pd.DataFrame(seed_metrics)
    agg = {
        "model"        : model_name,
        "mAP50_mean"   : df["mAP50"].mean(),
        "mAP50_std"    : df["mAP50"].std(),
        "mAP5095_mean" : df["mAP50_95"].mean(),
        "mAP5095_std"  : df["mAP50_95"].std(),
        "prec_mean"    : df["precision"].mean(),
        "prec_std"     : df["precision"].std(),
        "rec_mean"     : df["recall"].mean(),
        "rec_std"      : df["recall"].std(),
        "train_hr_mean": df["train_hr"].mean(),
        "per_seed"     : seed_metrics,
        "fcr"          : seed_fcr,
        "per_class_df" : pd.concat(per_class_frames, ignore_index=True).to_dict("records"),
    }
    fcr_macros      = [s["macro_FCR"] for s in seed_fcr if s["macro_FCR"] is not None]
    agg["FCR_mean"]  = np.mean(fcr_macros) if fcr_macros else None
    agg["FCR_std"]   = np.std(fcr_macros)  if fcr_macros else None
    return agg

print("✓ train_model() defined")

