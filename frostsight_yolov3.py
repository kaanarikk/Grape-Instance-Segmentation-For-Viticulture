"""## 🔲 Cell 21 — Instance Segmentation vs Bounding Box [R2-B]

> Directly answers Reviewer 2's question: how much does the mask head add over the bbox head?
"""

def plot_seg_vs_bbox(results: list):
    """
    Tüm modeller için Box mAP50 ve mAP50-95 karşılaştırması.
    Segmentation modeller için Mask metriği de eklenir.
    RT-DETR ve OBB → sadece Box metriği (detection-only).
    """
    from ultralytics import YOLO

    model_names, box50, box95, seg50, seg95 = [], [], [], [], []

    for r in results:
        best_pt = r["per_seed"][-1].get("best_weights", "")
        if not os.path.exists(best_pt):
            print(f"[SEG-BBOX] {r['model']} weights bulunamadı, atlandı.")
            continue

        print(f"[SEG-BBOX] Validating {r['model']} …")
        val_r = YOLO(best_pt).val(
            data    = data_yaml,
            split   = "test",
            imgsz   = CFG["img_size"],
            device  = CFG["device"],
            verbose = False,
        )
        d = val_r.results_dict

        model_names.append(r["model"])
        box50.append( d.get("metrics/mAP50(B)",    0))
        box95.append( d.get("metrics/mAP50-95(B)", 0))
        # RT-DETR ve OBB mask metriği olmadığı için 0 gelir, None olarak işaretle
        m50  = d.get("metrics/mAP50(M)",    None)
        m95  = d.get("metrics/mAP50-95(M)", None)
        seg50.append( m50 if (m50 and m50 > 0) else None)
        seg95.append( m95 if (m95 and m95 > 0) else None)

    if not model_names:
        print("[SEG-BBOX] Hiç model bulunamadı."); return

    n      = len(model_names)
    x      = np.arange(n)
    w      = 0.25
    colors = {"box50": "#4C72B0", "box95": "#7BA3D4",
               "seg50": "#DD8452", "seg95": "#F0B484"}

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))

    for ax, b_vals, s_vals, metric_label in [
        (axes[0], box50,  seg50,  "mAP@50"),
        (axes[1], box95,  seg95,  "mAP@50-95"),
    ]:
        # Box bars
        bars_box = ax.bar(x - w/2, b_vals, w,
                          label="BBox", color=colors["box50"] if "50" in metric_label else colors["box95"],
                          edgecolor="black", linewidth=0.7)

        # Mask bars (None olanlar 0 gösterilir, çizgili)
        mask_vals = [v if v is not None else 0 for v in s_vals]
        bars_seg  = ax.bar(x + w/2, mask_vals, w,
                           label="Mask (seg only)",
                           color=colors["seg50"] if "50" in metric_label else colors["seg95"],
                           edgecolor="black", linewidth=0.7)

        # N/A olan barları çizgili göster
        for i, v in enumerate(s_vals):
            if v is None:
                bars_seg[i].set_hatch("///")
                bars_seg[i].set_alpha(0.4)
                ax.text(x[i] + w/2, 0.02, "N/A",
                        ha="center", va="bottom", fontsize=8, color="gray")

        # Değer label'ları
        for bar in bars_box:
            h = bar.get_height()
            if h > 0:
                ax.text(bar.get_x() + bar.get_width()/2, h + 0.008,
                        f"{h:.3f}", ha="center", va="bottom", fontsize=8, fontweight="bold")
        for bar, v in zip(bars_seg, s_vals):
            if v is not None and v > 0:
                ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.008,
                        f"{v:.3f}", ha="center", va="bottom", fontsize=8, fontweight="bold")

        ax.set_xticks(x)
        ax.set_xticklabels(model_names, rotation=15, ha="right", fontsize=10)
        ax.set_ylabel(metric_label, fontsize=11)
        ax.set_title(f"BBox vs Mask – {metric_label}", fontsize=12, fontweight="bold")
        ax.set_ylim(0, 1.0)
        ax.legend(fontsize=10)
        ax.grid(axis="y", alpha=0.3)

        # N/A legend
        from matplotlib.patches import Patch
        na_patch = Patch(facecolor="gray", alpha=0.4, hatch="///", label="Mask N/A (det-only)")
        handles, labels = ax.get_legend_handles_labels()
        ax.legend(handles=handles + [na_patch],
                  labels=labels + ["Mask N/A (det-only)"],
                  fontsize=9)

    plt.suptitle("Bounding Box vs Instance Segmentation – Tüm Modeller [R2-B]",
                 fontsize=13, fontweight="bold")
    plt.tight_layout()
    path = os.path.join(CFG["output_dir"], "fig_seg_vs_bbox.png")
    plt.savefig(path, dpi=150, bbox_inches="tight")
    plt.show()
    print(f"[PLOT] Saved → {path}")

    # Özet tablo
    print("\n" + "="*65)
    print(f"{'Model':<20} {'Box mAP50':>10} {'Box mAP95':>10} {'Mask mAP50':>11} {'Mask mAP95':>11}")
    print("-"*65)
    for name, b5, b9, s5, s9 in zip(model_names, box50, box95, seg50, seg95):
        s5_str = f"{s5:.4f}" if s5 else "  N/A"
        s9_str = f"{s9:.4f}" if s9 else "  N/A"
        print(f"{name:<20} {b5:>10.4f} {b9:>10.4f} {s5_str:>11} {s9_str:>11}")

